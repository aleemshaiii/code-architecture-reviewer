import io
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle

class ReportGenerator:
    @staticmethod
    def generate_pdf(review_data: dict) -> io.BytesIO:
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
        elements = []
        styles = getSampleStyleSheet()

        title_style = ParagraphStyle(
            'TitleStyle',
            parent=styles['Heading1'],
            fontSize=18,
            textColor=colors.HexColor('#0284c7'),
            spaceAfter=12
        )
        h2_style = ParagraphStyle(
            'Heading2Style',
            parent=styles['Heading2'],
            fontSize=13,
            textColor=colors.HexColor('#1e293b'),
            spaceBefore=10,
            spaceAfter=6
        )
        body_style = ParagraphStyle(
            'BodyStyle',
            parent=styles['Normal'],
            fontSize=9,
            textColor=colors.HexColor('#334155'),
            leading=12
        )

        elements.append(Paragraph("Code & Architecture Review Audit Report", title_style))
        elements.append(Paragraph("Generated by Real-Time Multimodal Reviewer Pipeline", body_style))
        elements.append(Spacer(1, 14))

        # Metrics Table
        metrics = review_data.get("ast", {}).get("metrics", {})
        metric_data = [
            ["Metric", "Value", "Metric", "Value"],
            ["Total Lines", str(metrics.get("total_lines", 0)), "Functions", str(metrics.get("function_count", 0))],
            ["Imports", str(metrics.get("import_count", 0)), "Flags / Warnings", str(metrics.get("warning_count", 0))]
        ]
        t = Table(metric_data, colWidths=[120, 140, 120, 140])
        t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#0f172a')),
            ('TEXTCOLOR', (0, 0), (-1, 0), colors.whitesmoke),
            ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
            ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
            ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#cbd5e1')),
        ]))
        elements.append(t)
        elements.append(Spacer(1, 14))

        # AST Warnings
        elements.append(Paragraph("AST Structural Warnings", h2_style))
        warnings = review_data.get("ast", {}).get("warnings", [])
        if warnings:
            for w in warnings:
                msg = f"<b>Line {w.get('line', '?')} [{w.get('type')}]:</b> {w.get('message')}"
                elements.append(Paragraph(msg, body_style))
                elements.append(Spacer(1, 4))
        else:
            elements.append(Paragraph("No AST warnings detected.", body_style))

        elements.append(Spacer(1, 10))

        # FAISS Rules
        elements.append(Paragraph("Triggered Best Practice & Security Rules", h2_style))
        rules = review_data.get("relevant_rules", [])
        if rules:
            for r in rules:
                rule_text = f"<b>{r.get('id')} - {r.get('title')}</b> ({r.get('category')}): {r.get('content')}"
                elements.append(Paragraph(rule_text, body_style))
                elements.append(Spacer(1, 4))
        else:
            elements.append(Paragraph("No rules triggered.", body_style))

        doc.build(elements)
        buffer.seek(0)
        return buffer

report_generator = ReportGenerator()
